//! The catalog queries of a schema compare. Each source gives the same row shapes:
//!
//! - Columns: table, name, type, nullable (`yes` or `no`), default, generation of a
//!   value (identity, `serial`, `AUTO_INCREMENT`), generated clause, place in the primary
//!   key, `ON UPDATE` clause, and character set clause.
//! - Constraints: table, name, kind (`p`, `u`, `f`, or `c`), definition, place, column,
//!   target schema, target table, and target column.
//! - Indexes: table, name, unique (`yes` or `no`), place, column or expression, definition,
//!   prefix length, descending (`yes` or `no`), and expression.
//! - SQLite only, a fourth query: the type, the name, and the SQL text of each table and
//!   index.
//!
//! On PostgreSQL the read runs with the schema in `search_path`, so the database writes
//! the names of that schema without the schema.

use crate::catalog::RelationRef;
use crate::sql::{Dialect, quote_identifier};
use crate::structure::name_literal;
use crate::table::from_clause;

/// Returns the queries of the read of a schema. Redis has no tables.
pub fn compare_sql(dialect: Dialect, schema: &str) -> Option<Vec<String>> {
    let literal = name_literal(schema, dialect);
    match dialect {
        Dialect::Postgres => Some(vec![
            postgres_columns(&literal, ""),
            postgres_constraints(&literal),
            postgres_indexes(&literal),
        ]),
        Dialect::MySql => Some(vec![
            mysql_columns(&literal, ""),
            mysql_constraints(&literal),
            mysql_indexes(&literal),
        ]),
        Dialect::Sqlite => Some(vec![
            sqlite_columns(&literal, ""),
            sqlite_constraints(&literal),
            sqlite_indexes(&literal),
            sqlite_objects(&quote_identifier(schema, dialect)),
        ]),
        Dialect::Redis => None,
    }
}

/// Returns the column query of one table, with the shape of the first query of
/// `compare_sql`. A data compare reads the key and the generated columns from it.
pub fn table_columns_sql(dialect: Dialect, schema: &str, table: &str) -> Option<String> {
    let literal = name_literal(schema, dialect);
    let name = name_literal(table, dialect);
    match dialect {
        Dialect::Postgres => Some(postgres_columns(
            &literal,
            &format!(" AND c.relname = {name}"),
        )),
        Dialect::MySql => Some(mysql_columns(
            &literal,
            &format!(" AND c.TABLE_NAME = {name}"),
        )),
        Dialect::Sqlite => Some(sqlite_columns(&literal, &format!(" AND t.name = {name}"))),
        Dialect::Redis => None,
    }
}

/// Returns the read of each row of a table.
pub fn rows_sql(dialect: Dialect, schema: &str, table: &str) -> String {
    let relation = RelationRef {
        schema: schema.to_owned(),
        relation: table.to_owned(),
    };
    format!("SELECT * FROM {}", from_clause(&relation, dialect))
}

/// The tables of PostgreSQL: plain, partitioned, and foreign tables, without partitions.
const POSTGRES_TABLES: &str = "c.relkind IN ('r', 'p', 'f') AND NOT c.relispartition";

fn postgres_columns(schema: &str, filter: &str) -> String {
    format!(
        "SELECT c.relname::text AS relation, a.attname::text AS name, \
         pg_catalog.format_type(a.atttypid, a.atttypmod) AS type, \
         CASE WHEN a.attnotnull THEN 'no' ELSE 'yes' END AS nullable, \
         CASE WHEN a.attgenerated = '' AND s.serial IS NULL \
           THEN pg_catalog.pg_get_expr(d.adbin, d.adrelid) END AS \"default\", \
         CASE a.attidentity WHEN 'a' THEN 'GENERATED ALWAYS AS IDENTITY' \
           WHEN 'd' THEN 'GENERATED BY DEFAULT AS IDENTITY' ELSE s.serial END AS auto, \
         CASE WHEN a.attgenerated = 's' THEN 'GENERATED ALWAYS AS (' \
           || pg_catalog.pg_get_expr(d.adbin, d.adrelid) || ') STORED' END AS generated, \
         (SELECT k.place FROM pg_catalog.pg_index i \
            CROSS JOIN LATERAL pg_catalog.unnest(i.indkey::pg_catalog.int2[]) \
              WITH ORDINALITY AS k(attnum, place) \
          WHERE i.indrelid = c.oid AND i.indisprimary AND k.attnum = a.attnum) AS primary_key, \
         NULL::text AS on_update, NULL::text AS charset \
         FROM pg_catalog.pg_attribute a \
         JOIN pg_catalog.pg_class c ON c.oid = a.attrelid \
         JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace \
         LEFT JOIN pg_catalog.pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum \
         CROSS JOIN LATERAL (SELECT CASE WHEN a.attidentity = '' \
           AND pg_catalog.pg_get_serial_sequence( \
             pg_catalog.quote_ident(n.nspname) || '.' || pg_catalog.quote_ident(c.relname), \
             a.attname::text) IS NOT NULL THEN 'serial' END AS serial) s \
         WHERE a.attnum > 0 AND NOT a.attisdropped AND {POSTGRES_TABLES} \
           AND n.nspname = {schema}{filter} \
         ORDER BY c.relname, a.attnum"
    )
}

/// The constraint that a partition copies from its parent stays out.
fn postgres_constraints(schema: &str) -> String {
    format!(
        "SELECT c.relname::text AS relation, k.conname::text AS name, k.contype::text AS kind, \
         pg_catalog.pg_get_constraintdef(k.oid) AS definition, u.place AS place, \
         a.attname::text AS column_name, rn.nspname::text AS target_schema, \
         r.relname::text AS target_relation, ra.attname::text AS target_column \
         FROM pg_catalog.pg_constraint k \
         JOIN pg_catalog.pg_class c ON c.oid = k.conrelid \
         JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace \
         LEFT JOIN pg_catalog.pg_class r ON r.oid = k.confrelid \
         LEFT JOIN pg_catalog.pg_namespace rn ON rn.oid = r.relnamespace \
         LEFT JOIN LATERAL ROWS FROM \
           (pg_catalog.unnest(k.conkey), pg_catalog.unnest(k.confkey)) \
           WITH ORDINALITY AS u(attnum, target_attnum, place) ON k.contype IN ('u', 'f') \
         LEFT JOIN pg_catalog.pg_attribute a ON a.attrelid = k.conrelid AND a.attnum = u.attnum \
         LEFT JOIN pg_catalog.pg_attribute ra \
           ON ra.attrelid = k.confrelid AND ra.attnum = u.target_attnum \
         WHERE k.contype IN ('p', 'u', 'f', 'c') AND k.conparentid = 0 AND {POSTGRES_TABLES} \
           AND n.nspname = {schema} \
         ORDER BY c.relname, k.conname, u.place"
    )
}

/// An index of a primary key, a unique key, or an exclusion constraint stays out, because
/// its constraint holds it.
fn postgres_indexes(schema: &str) -> String {
    format!(
        "SELECT c.relname::text AS relation, ic.relname::text AS name, \
         CASE WHEN i.indisunique THEN 'yes' ELSE 'no' END AS \"unique\", k.place AS place, \
         pg_catalog.pg_get_indexdef(i.indexrelid, k.place, true) AS part, \
         pg_catalog.pg_get_indexdef(i.indexrelid) AS definition, NULL::text AS sub_part, \
         'no' AS descending, NULL::text AS expression \
         FROM pg_catalog.pg_index i \
         JOIN pg_catalog.pg_class ic ON ic.oid = i.indexrelid \
         JOIN pg_catalog.pg_class c ON c.oid = i.indrelid \
         JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace \
         CROSS JOIN LATERAL pg_catalog.generate_series(1, i.indnkeyatts::integer) AS k(place) \
         WHERE {POSTGRES_TABLES} AND n.nspname = {schema} \
           AND NOT EXISTS (SELECT 1 FROM pg_catalog.pg_constraint x \
             WHERE x.conrelid = i.indrelid AND x.conindid = i.indexrelid \
               AND x.contype IN ('p', 'u', 'x')) \
         ORDER BY c.relname, ic.relname, k.place"
    )
}

/// A text default becomes a literal, and a default of an expression keeps its form.
fn mysql_columns(schema: &str, filter: &str) -> String {
    format!(
        "SELECT c.TABLE_NAME AS relation, c.COLUMN_NAME AS name, c.COLUMN_TYPE AS type, \
         LOWER(c.IS_NULLABLE) AS nullable, \
         CASE WHEN c.COLUMN_DEFAULT IS NULL THEN NULL \
           WHEN c.EXTRA LIKE '%DEFAULT_GENERATED%' THEN \
             CASE WHEN c.COLUMN_DEFAULT LIKE 'CURRENT\\_TIMESTAMP%' THEN c.COLUMN_DEFAULT \
               ELSE CONCAT('(', c.COLUMN_DEFAULT, ')') END \
           ELSE QUOTE(c.COLUMN_DEFAULT) END AS `default`, \
         CASE WHEN c.EXTRA LIKE '%auto_increment%' THEN 'AUTO_INCREMENT' END AS auto, \
         CASE WHEN c.GENERATION_EXPRESSION <> '' THEN CONCAT('GENERATED ALWAYS AS (', \
           c.GENERATION_EXPRESSION, ') ', \
           CASE WHEN c.EXTRA LIKE '%STORED GENERATED%' THEN 'STORED' ELSE 'VIRTUAL' END) \
           END AS `generated`, \
         k.ORDINAL_POSITION AS primary_key, \
         CASE WHEN c.EXTRA LIKE '%on update %' THEN CONCAT('ON UPDATE ', \
           SUBSTRING(c.EXTRA, LOCATE('on update ', c.EXTRA) + 10)) END AS on_update, \
         CASE WHEN c.CHARACTER_SET_NAME IS NOT NULL THEN CONCAT('CHARACTER SET ', \
           c.CHARACTER_SET_NAME, ' COLLATE ', c.COLLATION_NAME) END AS `charset` \
         FROM information_schema.COLUMNS c \
         JOIN information_schema.TABLES t \
           ON t.TABLE_SCHEMA = c.TABLE_SCHEMA AND t.TABLE_NAME = c.TABLE_NAME \
         LEFT JOIN information_schema.KEY_COLUMN_USAGE k \
           ON k.TABLE_SCHEMA = c.TABLE_SCHEMA AND k.TABLE_NAME = c.TABLE_NAME \
           AND k.COLUMN_NAME = c.COLUMN_NAME AND k.CONSTRAINT_NAME = 'PRIMARY' \
         WHERE c.TABLE_SCHEMA = {schema} AND t.TABLE_TYPE = 'BASE TABLE'{filter} \
         ORDER BY c.TABLE_NAME, c.ORDINAL_POSITION"
    )
}

/// The foreign keys and the checks. The primary key comes with the columns, and a unique
/// key of MySQL is an index.
fn mysql_constraints(schema: &str) -> String {
    format!(
        "SELECT k.TABLE_NAME AS relation, k.CONSTRAINT_NAME AS name, 'f' AS kind, \
         CONCAT('ON UPDATE ', r.UPDATE_RULE, ' ON DELETE ', r.DELETE_RULE) AS definition, \
         k.ORDINAL_POSITION AS place, k.COLUMN_NAME AS column_name, \
         k.REFERENCED_TABLE_SCHEMA AS target_schema, k.REFERENCED_TABLE_NAME AS target_relation, \
         k.REFERENCED_COLUMN_NAME AS target_column \
         FROM information_schema.KEY_COLUMN_USAGE k \
         JOIN information_schema.REFERENTIAL_CONSTRAINTS r \
           ON r.CONSTRAINT_SCHEMA = k.CONSTRAINT_SCHEMA AND r.TABLE_NAME = k.TABLE_NAME \
           AND r.CONSTRAINT_NAME = k.CONSTRAINT_NAME \
         WHERE k.TABLE_SCHEMA = {schema} AND k.REFERENCED_TABLE_NAME IS NOT NULL \
         UNION ALL \
         SELECT t.TABLE_NAME, t.CONSTRAINT_NAME, 'c', h.CHECK_CLAUSE, NULL, NULL, NULL, NULL, NULL \
         FROM information_schema.TABLE_CONSTRAINTS t \
         JOIN information_schema.CHECK_CONSTRAINTS h \
           ON h.CONSTRAINT_SCHEMA = t.CONSTRAINT_SCHEMA AND h.CONSTRAINT_NAME = t.CONSTRAINT_NAME \
         WHERE t.TABLE_SCHEMA = {schema} AND t.CONSTRAINT_TYPE = 'CHECK' \
         ORDER BY 1, 2, 5"
    )
}

/// The index of the primary key, and the index that MySQL makes for a foreign key with
/// its name, stay out.
fn mysql_indexes(schema: &str) -> String {
    format!(
        "SELECT s.TABLE_NAME AS relation, s.INDEX_NAME AS name, \
         CASE WHEN s.NON_UNIQUE = 0 THEN 'yes' ELSE 'no' END AS `unique`, \
         s.SEQ_IN_INDEX AS place, s.COLUMN_NAME AS part, s.INDEX_TYPE AS definition, \
         s.SUB_PART AS sub_part, CASE WHEN s.COLLATION = 'D' THEN 'yes' ELSE 'no' END AS descending, \
         s.EXPRESSION AS expression \
         FROM information_schema.STATISTICS s \
         WHERE s.TABLE_SCHEMA = {schema} AND s.INDEX_NAME <> 'PRIMARY' \
           AND NOT EXISTS (SELECT 1 FROM information_schema.TABLE_CONSTRAINTS t \
             WHERE t.TABLE_SCHEMA = s.TABLE_SCHEMA AND t.TABLE_NAME = s.TABLE_NAME \
               AND t.CONSTRAINT_NAME = s.INDEX_NAME AND t.CONSTRAINT_TYPE = 'FOREIGN KEY') \
         ORDER BY s.TABLE_NAME, s.INDEX_NAME, s.SEQ_IN_INDEX"
    )
}

/// The tables of the system, the views, and the shadow tables stay out.
const SQLITE_TABLES: &str = "\
    t.type = 'table' AND t.name NOT LIKE 'sqlite\\_%' ESCAPE '\\'";

fn sqlite_columns(schema: &str, filter: &str) -> String {
    format!(
        "SELECT t.name AS relation, c.name AS name, c.type AS type, \
         CASE WHEN c.\"notnull\" = 0 THEN 'yes' ELSE 'no' END AS nullable, \
         c.dflt_value AS \"default\", NULL AS auto, \
         CASE c.hidden WHEN 2 THEN 'VIRTUAL' WHEN 3 THEN 'STORED' END AS generated, \
         NULLIF(c.pk, 0) AS primary_key, NULL AS on_update, NULL AS charset \
         FROM pragma_table_list t \
         JOIN pragma_table_xinfo(t.name, t.schema) c \
         WHERE t.schema = {schema} AND {SQLITE_TABLES} AND c.hidden <> 1{filter} \
         ORDER BY t.name, c.cid"
    )
}

/// The foreign keys and the unique keys of the table text. A foreign key has a number
/// and no name. A key without target columns reads the primary key of its target.
fn sqlite_constraints(schema: &str) -> String {
    format!(
        "SELECT t.name AS relation, f.id AS name, 'f' AS kind, \
         'ON UPDATE ' || f.on_update || ' ON DELETE ' || f.on_delete AS definition, \
         f.seq + 1 AS place, f.\"from\" AS column_name, NULL AS target_schema, \
         f.\"table\" AS target_relation, f.\"to\" AS target_column \
         FROM pragma_table_list t \
         JOIN pragma_foreign_key_list(t.name, t.schema) f \
         WHERE t.schema = {schema} AND {SQLITE_TABLES} \
         UNION ALL \
         SELECT t.name, l.name, 'u', NULL, x.seqno + 1, x.name, NULL, NULL, NULL \
         FROM pragma_table_list t \
         JOIN pragma_index_list(t.name, t.schema) l \
         JOIN pragma_index_info(l.name, t.schema) x \
         WHERE t.schema = {schema} AND {SQLITE_TABLES} AND l.origin = 'u' \
         ORDER BY 1, 2, 5"
    )
}

/// The indexes of `CREATE INDEX`. The fourth query gives their text.
fn sqlite_indexes(schema: &str) -> String {
    format!(
        "SELECT t.name AS relation, l.name AS name, \
         CASE WHEN l.\"unique\" THEN 'yes' ELSE 'no' END AS \"unique\", x.seqno + 1 AS place, \
         x.name AS part, NULL AS definition, NULL AS sub_part, \
         CASE WHEN x.\"desc\" THEN 'yes' ELSE 'no' END AS descending, NULL AS expression \
         FROM pragma_table_list t \
         JOIN pragma_index_list(t.name, t.schema) l \
         JOIN pragma_index_xinfo(l.name, t.schema) x \
         WHERE t.schema = {schema} AND {SQLITE_TABLES} AND l.origin = 'c' AND x.key = 1 \
         ORDER BY t.name, l.name, x.seqno"
    )
}

fn sqlite_objects(schema: &str) -> String {
    format!(
        "SELECT type, name, tbl_name, sql FROM {schema}.sqlite_schema \
         WHERE type IN ('table', 'index') AND sql IS NOT NULL \
           AND name NOT LIKE 'sqlite\\_%' ESCAPE '\\' \
         ORDER BY type, name"
    )
}
